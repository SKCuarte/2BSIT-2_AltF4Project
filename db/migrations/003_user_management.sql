CREATE TABLE IF NOT EXISTS public.role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE CHECK (name IN ('Superadmin', 'Admin', 'User')),
    description TEXT NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM'))
);

CREATE TABLE IF NOT EXISTS public.module (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL UNIQUE,
    sort_order SMALLINT NOT NULL UNIQUE,
    status VARCHAR(8) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM'))
);

CREATE TABLE IF NOT EXISTS public.rights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    module_id BIGINT NOT NULL REFERENCES public.module(id) ON DELETE RESTRICT,
    action VARCHAR(30) NOT NULL,
    label VARCHAR(100) NOT NULL,
    sort_order SMALLINT NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM')),
    UNIQUE (module_id, sort_order)
);

CREATE TABLE IF NOT EXISTS public.app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash TEXT,
    role_id BIGINT NOT NULL REFERENCES public.role(id) ON DELETE RESTRICT,
    employee_id VARCHAR(5) UNIQUE REFERENCES public."EMPLOYEE"(employee_id) ON DELETE SET NULL,
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    must_set_password BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    locked_until TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    status VARCHAR(8) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM')),
    CHECK (must_set_password OR password_hash IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.user_permission (
    user_id BIGINT NOT NULL REFERENCES public.app_user(id) ON DELETE RESTRICT,
    right_id BIGINT NOT NULL REFERENCES public.rights(id) ON DELETE RESTRICT,
    granted_by BIGINT NOT NULL REFERENCES public.app_user(id) ON DELETE RESTRICT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(8) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM')),
    PRIMARY KEY (user_id, right_id)
);

COMMENT ON TABLE public.role IS 'Account role catalogue. Superadmin receives all active rights implicitly.';
COMMENT ON TABLE public.module IS 'Permission catalogue modules shown in the rights-management screen.';
COMMENT ON TABLE public.rights IS 'Permission catalogue; codes are stable identifiers and labels are UI checkbox text.';
COMMENT ON TABLE public.app_user IS 'Application login identity. Password hashes are generated by the application.';
COMMENT ON COLUMN public.app_user.email IS 'Stored lowercase and uniquely indexed for case-insensitive identity lookup.';
COMMENT ON COLUMN public.app_user.password_hash IS 'Nullable until the first password is set; plaintext passwords must never be stored.';
COMMENT ON COLUMN public.app_user.employee_id IS 'Optional one-to-one link to EMPLOYEE. It is not SALES.employee_id or an audit actor identity.';
COMMENT ON COLUMN public.app_user.is_blocked IS 'Blocks sign-in without changing or deleting user_permission rows.';
COMMENT ON COLUMN public.app_user.must_set_password IS 'When true, password_hash may remain NULL until password setup completes.';
COMMENT ON TABLE public.user_permission IS 'Current permission grants. Revoke and restore by changing status; do not physically delete rows.';
COMMENT ON COLUMN public.user_permission.granted_by IS 'Admin or Superadmin who most recently granted or restored this permission.';
COMMENT ON COLUMN public.user_permission.granted_at IS 'Time this permission was most recently granted or restored.';
COMMENT ON COLUMN public.user_permission.stamp IS 'Only the latest grant/revoke action is retained; this is not a full audit history.';

CREATE OR REPLACE FUNCTION public.normalize_app_user_email_and_default_role()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.email := lower(btrim(NEW.email));

    IF NEW.role_id IS NULL THEN
        SELECT id INTO NEW.role_id
        FROM public.role
        WHERE name = 'User' AND status = 'Active';

        IF NEW.role_id IS NULL THEN
            RAISE EXCEPTION 'Active User role is required before creating an app_user';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_app_user_normalize_email_default_role
BEFORE INSERT OR UPDATE OF email, role_id ON public.app_user
FOR EACH ROW
EXECUTE FUNCTION public.normalize_app_user_email_and_default_role();

CREATE OR REPLACE FUNCTION public.enforce_user_permission_actor()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    actor_id BIGINT;
    actor_role TEXT;
    actor_status TEXT;
    actor_blocked BOOLEAN;
    actor_email TEXT;
    target_role TEXT;
    action_name TEXT;
BEGIN
    actor_id := NULLIF(current_setting('app.user_id', TRUE), '')::BIGINT;
    IF actor_id IS NULL THEN
        RAISE EXCEPTION 'app.user_id must be set by the authenticated server before changing permissions';
    END IF;

    SELECT role.name, account.status, account.is_blocked, account.email
    INTO actor_role, actor_status, actor_blocked, actor_email
    FROM public.app_user account
    JOIN public.role role ON role.id = account.role_id
    WHERE account.id = actor_id AND role.status = 'Active';

    IF actor_role IS NULL OR actor_role NOT IN ('Admin', 'Superadmin')
        OR actor_status <> 'Active' OR actor_blocked THEN
        RAISE EXCEPTION 'Only an active, unblocked Admin or Superadmin may change permissions';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Permissions cannot be physically deleted; set status = Inactive';
    ELSIF TG_OP = 'INSERT' THEN
        SELECT role.name INTO target_role
        FROM public.app_user account
        JOIN public.role role ON role.id = account.role_id
        WHERE account.id = NEW.user_id;

        IF target_role = 'Superadmin' THEN
            RAISE EXCEPTION 'Superadmin rights are implicit; do not create user_permission rows';
        END IF;
        IF NEW.status <> 'Active' THEN
            RAISE EXCEPTION 'Create a permission as Active; use a status update to revoke or restore it';
        END IF;
        NEW.granted_by := actor_id;
        NEW.granted_at := CURRENT_TIMESTAMP;
        action_name := 'CREATED';
    ELSE
        IF (NEW.user_id, NEW.right_id) IS DISTINCT FROM (OLD.user_id, OLD.right_id) THEN
            RAISE EXCEPTION 'Permission key columns are immutable';
        END IF;

        IF NEW.status IS DISTINCT FROM OLD.status THEN
            IF NEW.status = 'Active' THEN
                SELECT role.name INTO target_role
                FROM public.app_user account
                JOIN public.role role ON role.id = account.role_id
                WHERE account.id = NEW.user_id;
                IF target_role = 'Superadmin' THEN
                    RAISE EXCEPTION 'Superadmin rights are implicit; do not create user_permission rows';
                END IF;
                NEW.granted_by := actor_id;
                NEW.granted_at := CURRENT_TIMESTAMP;
                action_name := 'RESTORED';
            ELSE
                NEW.granted_by := OLD.granted_by;
                NEW.granted_at := OLD.granted_at;
                action_name := 'DELETED';
            END IF;
        ELSE
            IF NEW.granted_by IS DISTINCT FROM OLD.granted_by
                OR NEW.granted_at IS DISTINCT FROM OLD.granted_at THEN
                RAISE EXCEPTION 'Grant actor and time change only when a permission is granted or restored';
            END IF;
            action_name := 'EDITED';
        END IF;
    END IF;

    NEW.stamp := action_name || ' ' || actor_email || ' ' ||
        to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM');
    RETURN NEW;
END;
$$;

