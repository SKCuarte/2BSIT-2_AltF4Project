DO $$
BEGIN
    IF to_regrole('anon') IS NULL
        OR to_regrole('authenticated') IS NULL
        OR to_regrole('service_role') IS NULL THEN
        RAISE EXCEPTION 'Supabase anon, authenticated, and service_role roles are required';
    END IF;
END;
$$;

DO $$
DECLARE
    app_user_id_type TEXT;
BEGIN
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO app_user_id_type
    FROM pg_attribute AS attribute
    WHERE attribute.attrelid = 'public.app_user'::regclass
      AND attribute.attname = 'id'
      AND NOT attribute.attisdropped;

    IF app_user_id_type IS NULL THEN
        RAISE EXCEPTION 'public.app_user.id is required before creating password reset tokens';
    END IF;
    IF app_user_id_type NOT IN ('bigint', 'uuid') THEN
        RAISE EXCEPTION 'Unsupported public.app_user.id type for password reset tokens: %', app_user_id_type;
    END IF;

    EXECUTE format($ddl$
        CREATE TABLE public.password_reset_token (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id %s NOT NULL REFERENCES public.app_user(id) ON DELETE CASCADE,
            token_hash BYTEA NOT NULL UNIQUE
                CONSTRAINT password_reset_token_hash_length_check
                CHECK (octet_length(token_hash) = 32),
            purpose VARCHAR(20) NOT NULL
                CONSTRAINT password_reset_token_purpose_check
                CHECK (purpose IN ('set_password', 'reset_password')),
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            expires_at TIMESTAMPTZ NOT NULL,
            used_at TIMESTAMPTZ,
            requested_ip INET,
            status VARCHAR(8) NOT NULL DEFAULT 'Active'
                CONSTRAINT password_reset_token_status_check
                CHECK (status IN ('Active', 'Inactive')),
            stamp VARCHAR(80) NOT NULL DEFAULT ('CREATED system ' || to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD FMHH12:MI AM')),
            CONSTRAINT password_reset_token_expiry_check CHECK (expires_at > created_at)
        )
    $ddl$, app_user_id_type);
END;
$$;

CREATE INDEX idx_password_reset_token_expires_at
    ON public.password_reset_token (expires_at);

CREATE UNIQUE INDEX ux_password_reset_token_open_user_purpose
    ON public.password_reset_token (user_id, purpose)
    WHERE status = 'Active' AND used_at IS NULL;

COMMENT ON TABLE public.password_reset_token IS 'Stores only SHA-256 token digests for account password setup and reset. Raw tokens are generated and handled by server code only.';
COMMENT ON COLUMN public.password_reset_token.token_hash IS 'Exactly 32 SHA-256 digest bytes; never store the raw token.';
COMMENT ON COLUMN public.password_reset_token.used_at IS 'NULL until redeemed; the timestamp records when a token was consumed, unlike a boolean flag.';
COMMENT ON COLUMN public.password_reset_token.stamp IS 'Latest lifecycle action only; this is not a full audit history.';

ALTER TABLE public.password_reset_token ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.password_reset_token
    FROM PUBLIC, anon, authenticated;
GRANT ALL PRIVILEGES ON TABLE public.password_reset_token TO service_role;

DO $$
DECLARE
    token_sequence TEXT;
BEGIN
    token_sequence := pg_get_serial_sequence('public.password_reset_token', 'id');
    IF token_sequence IS NULL THEN
        RAISE EXCEPTION 'The password_reset_token identity sequence is required';
    END IF;

    EXECUTE format(
        'REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC, anon, authenticated',
        token_sequence
    );
    EXECUTE format(
        'GRANT USAGE, SELECT ON SEQUENCE %s TO service_role',
        token_sequence
    );
END;
$$;